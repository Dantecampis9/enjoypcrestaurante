const I18N = (() => {
  const STORAGE_KEY = "enjoy-lang";

  function detectLang() {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === "es" || saved === "en") return saved;
    return navigator.language && navigator.language.toLowerCase().startsWith("en") ? "en" : "es";
  }

  function translate(key, lang) {
    return (I18N_DICT[lang] && I18N_DICT[lang][key]) || (I18N_DICT.es[key]) || key;
  }

  function apply(lang) {
    document.documentElement.lang = lang;

    document.querySelectorAll("[data-i18n]").forEach((el) => {
      el.textContent = translate(el.getAttribute("data-i18n"), lang);
    });
    document.querySelectorAll("[data-i18n-html]").forEach((el) => {
      el.innerHTML = translate(el.getAttribute("data-i18n-html"), lang);
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
      el.setAttribute("placeholder", translate(el.getAttribute("data-i18n-placeholder"), lang));
    });
    document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
      el.setAttribute("aria-label", translate(el.getAttribute("data-i18n-aria"), lang));
    });
    document.querySelectorAll("[data-i18n-alt]").forEach((el) => {
      el.setAttribute("alt", translate(el.getAttribute("data-i18n-alt"), lang));
    });

    const titleKey = document.documentElement.getAttribute("data-i18n-title");
    if (titleKey) document.title = translate(titleKey, lang);

    const descKey = document.documentElement.getAttribute("data-i18n-description");
    const metaDesc = document.querySelector('meta[name="description"]');
    if (descKey && metaDesc) metaDesc.setAttribute("content", translate(descKey, lang));

    document.querySelectorAll("[data-lang-toggle]").forEach((btn) => {
      btn.setAttribute("aria-pressed", btn.getAttribute("data-lang-toggle") === lang);
    });
  }

  function setLang(lang) {
    localStorage.setItem(STORAGE_KEY, lang);
    apply(lang);
  }

  function init() {
    const lang = detectLang();
    apply(lang);
    document.querySelectorAll("[data-lang-toggle]").forEach((btn) => {
      btn.addEventListener("click", () => setLang(btn.getAttribute("data-lang-toggle")));
    });
    return lang;
  }

  return { init, setLang, translate, detectLang };
})();

I18N.init();
